package main

import (
	"testing"

	"github.com/sacloud/skr/test/e2e/internal/helper"
	"github.com/stretchr/testify/require"
)

const (
	// kmsKeyNamePrefix は今回の実行が作成するキー名の接頭辞です。
	kmsKeyNamePrefix = "skr-e2e-kms-"
	// kmsKeyDescription は今回の実行が設定するキー説明の接頭辞です。
	kmsKeyDescriptionPrefix = "skr-e2e-kms/"
	// kmsPlainText は暗号化と復号を確認する平文です。
	kmsPlainText = "HelloKMS"
)

// TestScenarioKmsKey は kms-api key コマンドのライブ E2E です。
// 生成モードのキー作成から、参照、一覧、名前と説明の更新、ローテーション、
// 暗号化と復号、削除予約とその取り消し、削除までの一連の操作を検証します。
// BYOK モードのキーも作成し、キー生成方法 (KeyOrigin) が imported になることを確認します。
// 作成するのは KMS キー 2 件のみで、テスト関数内で削除まで行います。
func TestScenarioKmsKey(t *testing.T) {
	h := helper.New(t, "kms-api",
		"KMS キーの作成・参照・一覧・更新・ローテーション・暗号化・復号・削除予約とその取り消し・削除が正しく動作することを確認する")

	suffix := helper.RandomSuffix(t)
	keyName := kmsKeyNamePrefix + suffix
	description := kmsKeyDescriptionPrefix + suffix
	renamedName := keyName + "-renamed"

	// 作成前に同名キーが存在しないことを確認する
	before := listKmsKeys(t, h, "作成前に同名キーが存在しないことを確認する")
	for _, item := range before {
		require.NotEqual(t, keyName, item.Name, "key name %q already exists; refusing to modify it", keyName)
		require.NotEqual(t, renamedName, item.Name, "key name %q already exists; refusing to modify it", renamedName)
	}

	// キーを作成する
	created := createKmsKey(t, h, keyName, description)
	require.NotEmpty(t, created.ID, "created key should have an ID: %+v", created)
	require.Equal(t, keyName, created.Name, "created key name should match the requested name")
	require.Equal(t, "active", created.Status, "new key should be active")
	require.Equal(t, "generated", created.KeyOrigin, "created key should be generated by the API")
	require.Equal(t, "cloud/kms/key", created.ServiceClass, "created key should use the standard service class")
	keyID := created.ID

	// 後片付け: 作成したキーを削除し、一覧に残っていないことを確認する
	defer func() {
		deleteKmsKey(t, h, keyID)
		remaining := listKmsKeys(t, h, "削除後にキーが一覧に残っていないことを確認する")
		for _, item := range remaining {
			require.NotEqual(t, keyID, item.ID, "key %q should not remain after deletion", keyID)
		}
	}()

	// BYOK モードのキーも作成する
	imported := createKmsKeyWithPlainKeyFile(t, h, keyName+"-byok", writeKmsPlainKeyFile(t))
	require.NotEmpty(t, imported.ID, "imported key should have an ID: %+v", imported)
	require.Equal(t, "imported", imported.KeyOrigin, "BYOK key should be imported")
	importedID := imported.ID

	// 後片付け: BYOK キーも作成直後に登録する
	defer func() {
		deleteKmsKey(t, h, importedID)
		remaining := listKmsKeys(t, h, "削除後にキーが一覧に残っていないことを確認する")
		for _, item := range remaining {
			require.NotEqual(t, importedID, item.ID, "key %q should not remain after deletion", importedID)
		}
	}()

	// 作成したキーを参照する
	read := readKmsKey(t, h, keyID)
	require.Equal(t, keyID, read.ID, "read should return the key created by this run")
	require.Equal(t, keyName, read.Name, "read key name should match the requested name")

	// 作成したキーが一覧に含まれることを確認する
	listed := listKmsKeys(t, h, "作成したキーが一覧に含まれることを確認する")
	matches := 0
	for _, item := range listed {
		if item.ID == keyID {
			require.Equal(t, keyName, item.Name, "listed key %q should be the key created by this run", keyID)
			matches++
		}
	}
	require.Equal(t, 1, matches, "key list should contain exactly one match for %q", keyID)

	// キーの名前と説明を更新する
	updated := updateKmsKey(t, h, keyID, renamedName, description+"-updated")
	require.Equal(t, keyID, updated.ID, "updated key should be the key created by this run")
	require.Equal(t, renamedName, updated.Name, "updated key name should match the requested name")

	// 更新後の名前が参照でも返ることを確認する
	reread := readKmsKey(t, h, keyID)
	require.Equal(t, renamedName, reread.Name, "read after update should return the updated name")

	// キーをローテーションする
	rotated := rotateKmsKey(t, h, keyID)
	require.Equal(t, keyID, rotated.ID, "rotated key should be the key created by this run")
	require.Greater(t, rotated.LatestVersion, created.LatestVersion,
		"rotation should increase the latest version: created=%d rotated=%d", created.LatestVersion, rotated.LatestVersion)

	// 平文を暗号化し、暗号文を復号して元の平文と一致することを確認する
	plainFile := writePlainFile(t, kmsPlainText)
	cipher := encryptKmsKey(t, h, keyID, plainFile)
	require.NotEmpty(t, cipher, "encrypt should return a ciphertext")
	decrypted := decryptKmsKey(t, h, keyID, writeCipherFile(t, []byte("\""+cipher+"\"")))
	require.Equal(t, kmsPlainText, decrypted, "decrypted plain text should match the encrypted plain text")

	// キーの状態を制限中に変更し、戻す
	require.Equal(t, "restricted", changeKmsKeyStatus(t, h, keyID, "restricted"),
		"change-status should return the new status")
	require.Equal(t, "restricted", readKmsKey(t, h, keyID).Status, "key status should be restricted")
	require.Equal(t, "active", changeKmsKeyStatus(t, h, keyID, "active"),
		"change-status should return the new status")
	require.Equal(t, "active", readKmsKey(t, h, keyID).Status, "key status should be active")

	// 削除を予約し、予約中のステータスと削除予定日時を確認してから取り消す
	scheduledStatus, deletionAfter := scheduleKmsKeyDestruction(t, h, keyID, 7)
	require.Equal(t, "pending_destruction", scheduledStatus, "schedule-destruction should reserve the deletion")
	require.NotEmpty(t, deletionAfter, "schedule-destruction should return the deletion scheduled time")
	require.Equal(t, "active", changeKmsKeyStatus(t, h, keyID, "active"),
		"changing the status back to active should cancel the deletion schedule")
	require.Equal(t, "active", readKmsKey(t, h, keyID).Status, "canceled key should be active again")
}
